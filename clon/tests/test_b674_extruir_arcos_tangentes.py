def _llamar(s, nombre, **args):
    r = api.llamar(s, nombre, args)
    assert r["ok"], r
    return r["result"]


def test_extruir_perfil_con_arcos_casi_tangentes_da_un_solido_valido():
    s = api.Sesion()
    _llamar(s, "create_sketch", plane="XY", name="S")
    for x1, y1, xm, ym, x2, y2 in ARCOS:
        _llamar(s, "draw_arc", sketch="S", start_x=x1, start_y=y1, mid_x=xm, mid_y=ym, end_x=x2, end_y=y2)
    for x1, y1, x2, y2 in LINEAS:
        _llamar(s, "draw_line", sketch="S", start_x=x1, start_y=y1, end_x=x2, end_y=y2)
    perfiles = _llamar(s, "get_sketch", sketch="S")["profiles"]
    banda = next(q for q in perfiles if abs(q["area"] - AREA_BANDA) < 0.01)
    _llamar(s, "extrude", profiles=[{"sketch": "S", "profile": banda["index"]}], distance=5, operation="new_body")
    vol = _llamar(s, "get_physical_properties")["total"]["volume"]
    assert abs(vol - AREA_BANDA * 5) < 0.5       # extrude ya falla si el cuerpo queda inválido
